# 1D Array

Names = ["Taha" , "Ahmed", "Ayaan" , "Bilal" , "Someone" , "drugs"]

#finding the length of the Array

LengthofArray = len(Names)
print(LengthofArray)

# printing out each array index

for x in range (len(Names)):
    print(Names[x])

